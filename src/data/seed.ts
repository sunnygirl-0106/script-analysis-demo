// ── 组装：把上面的 ShotSeed 平铺成 Record<id, Shot>，并生成 scenes / episode ──
function buildScene(
  episodeId: string,
  sceneId: string,
  no: number,
  name: string,
  location: string,
  timeOfDay: string,
  rawText: string,
  track: Scene['track'],
  seeds: ShotSeed[],
  shotStore: Record<string, Shot>,
): Scene {
  const shotIds = seeds.map((s, i) => {
    const id = `${sceneId}_sh${i + 1}`
    // 逐镜提示词在生成点统一注入；PROMPTS 缺条目时回退到 seed 里的一句话提示词。
    shotStore[id] = {
      ...s, id, sceneId, no: i + 1,
      imagePrompt: PROMPTS[id]?.image ?? s.imagePrompt,
      videoPrompt: PROMPTS[id]?.video ?? s.videoPrompt,
    }
    return id
  })
  return { id: sceneId, episodeId, no, name, location, timeOfDay, rawText, shotIds, density: 'standard', track }
}

