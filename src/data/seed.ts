// 挂载简写：把 seed 里「角色 + 服装 + 场景 + 道具」的 id 列表折叠成挂载引用。
//   · 角色 + 其服装（同一镜里共现）→ 该角色的着装 look；服装本身不单独挂（决策 3b）
//   · 只有角色、没有服装 → 保留 character 兜底挂载（页面出「未指定着装」告警）
const kindOf: Record<string, AssetKind> = Object.fromEntries(catalog.map((a) => [a.id, a.kind]))
const LOOK_BY_CHAR: Record<string, Look> = {}
for (const lk of looks) LOOK_BY_CHAR[lk.characterId] = lk

export const m = (...ids: string[]): MountRef[] => {
  const present = new Set(ids)
  const out: MountRef[] = []
  const seen = new Set<string>()
  const push = (kind: MountableKind, assetId: string) => {
    if (seen.has(assetId)) return
    seen.add(assetId)
    out.push({ kind, assetId })
  }
  for (const id of ids) {
    const kind = kindOf[id]
    if (kind === 'costume') continue // 服装并入 look，不单独挂
    if (kind === 'character') {
      const look = LOOK_BY_CHAR[id]
      if (look && look.costumeIds.some((cid) => present.has(cid))) push('look', look.id)
      else push('character', id) // 没给着装 → 角色兜底
      continue
    }
    push(kind as MountableKind, id) // location / prop
  }
  return out
}

